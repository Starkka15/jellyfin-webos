const assert = require('assert'), fs = require('fs'), path = require('path'), vm = require('vm');
const kinds = {}, requests = [];
function XHR() { requests.push(this); }
XHR.prototype.open = function(method, url) { this.url = url; };
XHR.prototype.send = function() {};
XHR.prototype.abort = function() { this.aborted = true; };
XHR.prototype.respond = function(data) { this.status = 200; this.responseText = JSON.stringify(data); this.readyState = 4; this.onreadystatechange(); };
const JF = {};
const sandbox = {JF, XMLHttpRequest: XHR, setTimeout, clearTimeout, miniBridgeBase: () => 'http://bridge/v1',
  enyo: {VFlexBox: {}, kind: definition => { kinds[definition.name] = definition; }}};
for (const name of ['NetworkLibrary.js', 'PlayerView.js']) vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../app/source', name), 'utf8'), sandbox);
let plan;
JF.networkPlaybackPlan('nas', ['film.mp4'], p => {plan = p;});
assert.strictEqual(plan.direct, 'http://bridge/v1/nas/film.mp4');
assert.strictEqual(requests.length, 0, 'MP4 starts without a probe');
JF.networkPlaybackPlan('alist', ['film.mkv'], p => {plan = p;});
requests.pop().respond({returnValue: true, video: {codec: 'hevc'}, miniSupported: true, durationSeconds: 120});
assert.strictEqual(plan.transcode, 'http://bridge/v1/library-transcode/alist/film.mkv');
assert.strictEqual(plan.duration, 120);
const tracks = JF.networkSubtitleTracks('nas', ['film.mp4'], [{name: 'film.zh.ass'}, {name: 'film.srt'}, {name: 'film-other.srt'}, {name: 'film.sup'}]);
assert.strictEqual(tracks.length, 2);
assert.strictEqual(tracks[0].url, 'http://bridge/v1/library-subtitle/nas/film.zh.ass');
const P = kinds['JF.PlayerView'];
let pending, starts = [];
JF.networkPlaybackPlan = (source, path, callback) => {pending = callback;};
const player = {playing: true, direct: true, waitingForRoute: false, request: {}, networkPlayback: {direct: 'direct', source: 'nas', path: ['film.mp4']},
  canChooseNetworkRoute: P.canChooseNetworkRoute, positionTicks: () => 420000000, startStream: t => starts.push(t), setStatus() {}, showControls() {}};
P.selectNetworkPlaybackMode.call(player, 'mini');
pending({transcode: 'converted'});
assert.strictEqual(player.networkTranscode, true);
assert.deepStrictEqual(starts, [420000000]);
P.selectNetworkPlaybackMode.call(player, 'auto');
assert.strictEqual(player.networkTranscode, false);
assert.deepStrictEqual(starts, [420000000, 420000000]);
player.networkPlayback = {direct: 'direct', source: 'nas', path: ['film.mp4']};
P.selectNetworkPlaybackMode.call(player, 'mini');
player.request = {};
pending({transcode: 'stale'});
assert.strictEqual(starts.length, 2, 'a seek or restart invalidates an outstanding probe');
let fallback;
player.request = {}; player.networkChecked = false; player.networkTranscode = false;
player.$ = {video: {setSrc() {}}};
player.tryNetworkTranscode = P.tryNetworkTranscode;
assert.strictEqual(P.tryNetworkTranscode.call(player), true);
fallback = pending; player.request = {};
fallback({transcode: 'stale'});
assert.strictEqual(starts.length, 2, 'a stale automatic fallback cannot restart playback');
const cues = JF.parseSrt('1\n00:00:01,000 --> 00:00:03,000\nHello\n\n2\n00:00:05,000 --> 00:00:06,000\nAgain');
assert.strictEqual(JF.subtitleAt(cues, 5.5), 'Again');
assert.strictEqual(JF.subtitleAt(cues, 1.5), 'Hello', 'cues still work after seeking backwards');
console.log('PASS: network direct-first, conversion, subtitle selection, route switching and stale probes');
